use super::*;

/// Supported shell targets for generated integration scripts.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum ShellKind {
    Bash,
}

/// Renders shell integration that wires configured navigation, titles, and completion into the shell.
pub(super) fn shell_init_script(shell: ShellKind, config: &ShellConfig) -> String {
    match shell {
        ShellKind::Bash => bash_init_script(config),
    }
}

/// Renders the current directory as a layout-aware shell prompt/title context.
pub(super) fn shell_title_context(
    config: &WorkflowConfig,
    environment: &RuntimeEnvironment,
) -> Result<String, RepositoryError> {
    let current_dir = shell_title_current_dir(environment);
    for root in current_dir.ancestors() {
        if let Some(context) = layout_title_context(config, root, &current_dir, environment)? {
            return Ok(context);
        }
    }

    Ok(fallback_title_context(&current_dir, environment))
}

fn bash_init_script(config: &ShellConfig) -> String {
    let mut script = bash_cli_completion_script();

    if config.title_enabled() {
        if !script.ends_with('\n') {
            script.push('\n');
        }
        script.push('\n');
        script.push_str(bash_title_script());
    }

    if let Some(command) = config.navigation_command() {
        if !script.ends_with('\n') {
            script.push('\n');
        }
        script.push('\n');
        script.push_str(&bash_navigation_script(
            command,
            config.navigation_tab_command(),
            config.zoxide,
        ));
    }

    script
}

fn shell_title_current_dir(environment: &RuntimeEnvironment) -> PathBuf {
    environment
        .variable("PWD")
        .filter(|pwd| !pwd.is_empty())
        .map(PathBuf::from)
        .filter(|pwd| pwd.is_absolute())
        .unwrap_or_else(|| environment.current_dir().to_path_buf())
}

fn layout_title_context(
    config: &WorkflowConfig,
    root: &Path,
    current_dir: &Path,
    environment: &RuntimeEnvironment,
) -> Result<Option<String>, RepositoryError> {
    let identity = match config.layout.identity_for_workspace_root(root, environment) {
        Ok(identity) => identity,
        Err(RepositoryError::LayoutPathNotMatched { .. })
        | Err(RepositoryError::AmbiguousLayoutPath { .. }) => return Ok(None),
        Err(error) => return Err(error),
    };

    let mut context = config.shell.repository_label(&identity);
    if let Some(workspace) =
        workspace_name_for_layout_root(&config.layout, &identity, root, environment)?
    {
        context.push('@');
        context.push_str(&workspace);
    }

    if let Ok(relative) = current_dir.strip_prefix(root) {
        if !relative.as_os_str().is_empty() {
            context.push('/');
            context.push_str(&relative.to_string_lossy());
        }
    }

    Ok(Some(context))
}

fn workspace_name_for_layout_root(
    layout: &LayoutConfig,
    identity: &RepositoryIdentity,
    root: &Path,
    environment: &RuntimeEnvironment,
) -> Result<Option<String>, RepositoryError> {
    if layout.project_destination(identity, environment)? == root {
        return Ok(None);
    }

    let collection_root = layout.workspace_collection_root(identity, environment)?;
    let Ok(relative) = root.strip_prefix(collection_root) else {
        return Ok(None);
    };
    let mut components = relative.components();
    let Some(std::path::Component::Normal(workspace)) = components.next() else {
        return Ok(None);
    };
    if components.next().is_some() {
        return Ok(None);
    }

    Ok(workspace.to_str().map(str::to_owned))
}

fn fallback_title_context(current_dir: &Path, environment: &RuntimeEnvironment) -> String {
    if let Some(home) = environment
        .variable("HOME")
        .filter(|home| !home.is_empty())
        .map(PathBuf::from)
    {
        if current_dir == home {
            return "~".to_owned();
        }
        if let Ok(relative) = current_dir.strip_prefix(&home) {
            return format!("~/{}", relative.display());
        }
    }

    current_dir.display().to_string()
}

fn bash_cli_completion_script() -> String {
    let mut command = cli();
    let mut output = Vec::new();
    clap_complete::generate(clap_complete::Shell::Bash, &mut command, "jx", &mut output);
    let mut script = String::from_utf8(output).expect("clap_complete emits valid UTF-8");
    script.push_str(bash_project_argument_completion_script());
    script.push_str(&bash_work_cd_script());
    script
}

fn bash_project_argument_completion_script() -> &'static str {
    r#"
# Generated by jx shell init bash: project argument completion.
__jx_work_delete_completion() {
  local cur="${COMP_WORDS[COMP_CWORD]}"
  local word
  local positional_count=0

  if [[ "$cur" == -* ]]; then
    _jx "$@"
    return
  fi

  for (( i = 3; i < COMP_CWORD; i++ )); do
    word="${COMP_WORDS[i]}"
    [[ "$word" == -* ]] && continue
    (( positional_count++ ))
  done

  if (( positional_count > 0 )); then
    COMPREPLY=()
    return
  fi

  local IFS=$'\n'
  COMPREPLY=($(compgen -W "$(command jx work complete --workspaces --prefix "$cur" 2>/dev/null)" -- "$cur"))
}

__jx_stack_reviewer_completion() {
  local cur="${COMP_WORDS[COMP_CWORD]}"
  local previous="${COMP_WORDS[COMP_CWORD-1]}"
  local previous2=""
  (( COMP_CWORD >= 2 )) && previous2="${COMP_WORDS[COMP_CWORD-2]}"
  local word candidate prefix
  local saw_stack=0
  local saw_publish=0

  for (( i = 1; i < COMP_CWORD; i++ )); do
    word="${COMP_WORDS[i]}"
    if (( saw_stack == 0 )); then
      case "$word" in
        stack|stk) saw_stack=1 ;;
      esac
      continue
    fi
    if (( saw_publish == 0 )); then
      case "$word" in
        publish|pub) saw_publish=1 ;;
      esac
      continue
    fi
  done

  (( saw_stack == 1 && saw_publish == 1 )) || return 1

  if [[ "$cur" == --reviewer=* ]]; then
    prefix="${cur#--reviewer=}"
    local IFS=$'\n'
    local candidates=()
    while IFS= read -r candidate; do
      [[ -n "$candidate" ]] && candidates+=("--reviewer=$candidate")
    done < <(command jx stack complete-reviewers --prefix "$prefix" 2>/dev/null)
    COMPREPLY=($(compgen -W "${candidates[*]}" -- "$cur"))
    return 0
  fi

  if [[ "$previous" == "=" && "$previous2" == "--reviewer" ]]; then
    local IFS=$'\n'
    COMPREPLY=($(compgen -W "$(command jx stack complete-reviewers --prefix "$cur" 2>/dev/null)" -- "$cur"))
    return 0
  fi

  if [[ "$previous" == "--reviewer" || "$previous" == "--reviewer=" || "$previous" == "-R" ]]; then
    local IFS=$'\n'
    COMPREPLY=($(compgen -W "$(command jx stack complete-reviewers --prefix "$cur" 2>/dev/null)" -- "$cur"))
    return 0
  fi

  return 1
}

__jx_project_arg_completion() {
  local cur="${COMP_WORDS[COMP_CWORD]}"
  local command=""
  local previous=""
  local word
  local positional_count=0
  local all_selected=0

  if [[ "${COMP_WORDS[1]}" == "work" && "${COMP_WORDS[2]}" == "delete" ]]; then
    __jx_work_delete_completion "$@"
    return
  fi

  if __jx_stack_reviewer_completion "$@"; then
    return
  fi

  for (( i = 1; i < COMP_CWORD; i++ )); do
    word="${COMP_WORDS[i]}"
    if [[ -z "$command" ]]; then
      case "$word" in
        remote-status|rs|fetch|f|sync|open|o) command="$word" ;;
      esac
      continue
    fi

    case "$previous" in
      --repo)
        previous=""
        (( positional_count++ ))
        continue
        ;;
      --jobs|-j)
        previous=""
        continue
        ;;
    esac

    case "$word" in
      -a|--all) [[ "$command" != "open" && "$command" != "o" ]] && all_selected=1 ;;
      --repo=*|--jobs=*) ;;
      -*) previous="$word" ;;
      pr|pull-request)
        (( positional_count++ ))
        ;;
      prs|pull-requests)
        if [[ ( "$command" == "open" || "$command" == "o" ) && $positional_count -eq 0 ]]; then
          :
        else
          (( positional_count++ ))
        fi
        ;;
      *) (( positional_count++ )) ;;
    esac
  done

  case "$previous" in
    --repo)
      local IFS=$'\n'
      COMPREPLY=($(compgen -W "$(command jx work complete --repositories --prefix "$cur" 2>/dev/null)" -- "$cur"))
      return
      ;;
    --jobs|-j)
      _jx "$@"
      return
      ;;
  esac

  if [[ -n "$command" && "$cur" != -* && $positional_count -eq 0 && $all_selected -eq 0 ]]; then
    local IFS=$'\n'
    COMPREPLY=($(compgen -W "$(command jx work complete --repositories --prefix "$cur" 2>/dev/null)" -- "$cur"))
  else
    _jx "$@"
  fi
}

complete -F __jx_project_arg_completion jx
"#
}

fn bash_work_cd_script() -> String {
    format!(
        r#"
# Generated by jx shell init bash: enter newly added workspaces, jump to trunk checkouts, and leave deleted ones safely.
jx() {{
  if [[ "$1" == "work" && ( "$2" == "add" || "$2" == "trunk" || "$2" == "delete" ) ]]; then
    local output status line cd_target=""
    output="$(command jx work "$2" --shell-cd-target "${{@:3}}")"
    status=$?
    if [[ -n "$output" ]]; then
      while IFS= read -r line; do
        case "$line" in
          {prefix}*) cd_target="${{line#{prefix}}}" ;;
          *) printf '%s\n' "$line" ;;
        esac
      done <<< "$output"
    fi
    if (( status == 0 )) && [[ -n "$cd_target" ]]; then
      if [[ "$2" == "delete" ]]; then
        cd "$cd_target"
      else
        pushd "$cd_target" > /dev/null
      fi
      status=$?
      (( status == 0 )) && dirs -v
    fi
    return $status
  fi

  command jx "$@"
}}
"#,
        prefix = SHELL_CD_TARGET_PREFIX,
    )
}

fn bash_title_script() -> &'static str {
    r#"# Generated by jx shell init bash: terminal titles and prompt context.
if [[ "${starship_precmd_user_func:-}" != "__jx_shell_title_precmd" ]]; then
  __jx_shell_title_previous_starship_precmd_user_func="${starship_precmd_user_func:-}"
elif [[ -z "${__jx_shell_title_previous_starship_precmd_user_func+x}" ]]; then
  __jx_shell_title_previous_starship_precmd_user_func=""
fi

__jx_shell_title_context_fallback() {
  if [[ -n "${HOME:-}" && "$PWD" == "$HOME" ]]; then
    printf '~'
  elif [[ -n "${HOME:-}" && "$PWD" == "$HOME"/* ]]; then
    printf '~/%s' "${PWD#"$HOME"/}"
  else
    printf '%s' "$PWD"
  fi
}

__jx_shell_title_context() {
  local context
  context="$(command jx shell title 2>/dev/null)" || context="$(__jx_shell_title_context_fallback)"
  printf '%s' "$context"
}

__jx_shell_title_set_zellij_tab_title() {
  local title="$1"
  if declare -F termflow_zellij_tab_title >/dev/null 2>&1; then
    termflow_zellij_tab_title "$title"
  elif declare -F jx_zellij_tab_title >/dev/null 2>&1; then
    jx_zellij_tab_title "$title"
  fi
}

jx_title() {
  local prefix="${1:-}"
  local context="${JX_WORK_CONTEXT:-}"
  if [[ -z "$context" ]]; then
    context="$(__jx_shell_title_context)"
  fi

  local title="$context"
  [[ -n "$prefix" ]] && title="$prefix: $title"
  printf '\033]0;%s\007' "$title"
  __jx_shell_title_set_zellij_tab_title "$title"
}

__jx_shell_title_update() {
  local context
  if [[ "${__jx_shell_title_pwd:-}" != "$PWD" || -z "${JX_WORK_CONTEXT+x}" ]]; then
    context="$(__jx_shell_title_context)"
    export JX_WORK_CONTEXT="$context"
    __jx_shell_title_pwd="$PWD"
  fi
  jx_title
}

__jx_shell_title_precmd() {
  local ret=$?
  if [[ -n "$__jx_shell_title_previous_starship_precmd_user_func" ]] && declare -F "$__jx_shell_title_previous_starship_precmd_user_func" >/dev/null 2>&1; then
    "$__jx_shell_title_previous_starship_precmd_user_func"
  fi
  __jx_shell_title_update
  return $ret
}

__jx_shell_title_install_prompt_command() {
  case ";${PROMPT_COMMAND:-};" in
    *";__jx_shell_title_precmd;"*) ;;
    *) PROMPT_COMMAND="__jx_shell_title_precmd${PROMPT_COMMAND:+;$PROMPT_COMMAND}" ;;
  esac
}

starship_precmd_user_func="__jx_shell_title_precmd"
if ! declare -F starship_precmd >/dev/null 2>&1; then
  __jx_shell_title_install_prompt_command
fi
"#
}

fn bash_navigation_script(
    command: &str,
    tab_command: Option<&str>,
    zoxide: ShellZoxideMode,
) -> String {
    let helper_prefix = helper_prefix(command);
    let zoxide_enabled_function = bash_navigation_zoxide_enabled_function(&helper_prefix, zoxide);
    let jx_first_key_function = bash_navigation_jx_first_key_function(&helper_prefix, zoxide);
    let zoxide_completion_function =
        bash_navigation_zoxide_completion_function(&helper_prefix, zoxide);
    let resolution = bash_navigation_resolution(&helper_prefix, zoxide);
    let prefer_completion = bash_navigation_prefer_completion(&helper_prefix, zoxide);
    let auto_zoxide_completion = bash_navigation_auto_zoxide_completion(&helper_prefix, zoxide);
    let zoxide_picker_completion = bash_navigation_zoxide_picker_completion(&helper_prefix, zoxide);
    let tab_function = bash_navigation_tab_function(&helper_prefix, tab_command);
    let tab_case = tab_command
        .map(|_| format!("    tab) {helper_prefix}_tab \"$@\" ;;\n"))
        .unwrap_or_default();
    let command_functions = bash_navigation_command_functions(&helper_prefix, command, tab_command);
    let completion_commands = tab_command.map_or_else(
        || command.to_owned(),
        |tab_command| format!("{command} {tab_command}"),
    );

    format!(
        r#"# Generated by jx shell init bash.
bind '"\e[0n": redraw-current-line' 2>/dev/null || true

{zoxide_enabled_function}{jx_first_key_function}{helper_prefix}_path_like() {{
  [[ "$1" == /* || "$1" == "." || "$1" == ".." || "$1" == ./* || "$1" == ../* ]]
}}

{helper_prefix}_cd() {{
  local ret
  pushd "$@" > /dev/null
  ret=$?
  (( ret == 0 )) && dirs -v
  return $ret
}}
{tab_function}
{helper_prefix}_navigate() {{
  local mode="$1"
  shift
  case "$mode" in
    cd) {helper_prefix}_cd "$@" ;;
{tab_case}    *) return 2 ;;
  esac
}}

{helper_prefix}_resolve_and_navigate() {{
  local mode="$1"
  shift
  local target

  if (( $# == 0 )); then
    target="$HOME"
  elif (( $# == 1 )) && {helper_prefix}_path_like "$1"; then
    {helper_prefix}_navigate "$mode" "$1"
    return $?
{resolution}  else
    {helper_prefix}_navigate "$mode" "$@"
    return $?
  fi

  {helper_prefix}_navigate "$mode" "$target"
}}

{command_functions}
{helper_prefix}_completion_cache_key=
{helper_prefix}_completion_cache_time=0
{helper_prefix}_completion_cache=
{helper_prefix}_completion_picker_cache_key=
{helper_prefix}_completion_picker_cache_time=0
{helper_prefix}_completion_picker_cache=

{helper_prefix}_jx_completion_candidates() {{
  local now
  now="$(date +%s 2>/dev/null)" || now=0
  if [[ "${{{helper_prefix}_completion_cache_key}}" != "$PWD" || $(( now - {helper_prefix}_completion_cache_time )) -ge 30 ]]; then
    {helper_prefix}_completion_cache="$(command jx work complete --navigation --prefix "" 2>/dev/null)"
    {helper_prefix}_completion_cache_key="$PWD"
    {helper_prefix}_completion_cache_time="$now"
  fi
  printf '%s\n' "${{{helper_prefix}_completion_cache}}"
}}

{helper_prefix}_jx_completion_picker_candidates() {{
  local now
  now="$(date +%s 2>/dev/null)" || now=0
  if [[ "${{{helper_prefix}_completion_picker_cache_key}}" != "$PWD" || $(( now - {helper_prefix}_completion_picker_cache_time )) -ge 30 ]]; then
    {helper_prefix}_completion_picker_cache="$(command jx work complete --navigation --format picker --prefix "" 2>/dev/null)"
    {helper_prefix}_completion_picker_cache_key="$PWD"
    {helper_prefix}_completion_picker_cache_time="$now"
  fi
  printf '%s\n' "${{{helper_prefix}_completion_picker_cache}}"
}}

{helper_prefix}_add_candidate() {{
  local candidate="$1" existing
  [[ -n "$candidate" ]] || return 0
  for existing in "${{candidates[@]}}"; do
    [[ "$existing" == "$candidate" ]] && return 0
  done
  candidates+=("$candidate")
}}

{helper_prefix}_add_picker_candidate() {{
  local key="$1" path="${{2:-}}" existing existing_key
  [[ -n "$key" ]] || return 0
  for existing in "${{picker_candidates[@]}}"; do
    existing_key="${{existing%%$'\t'*}}"
    [[ "$existing_key" == "$key" ]] && return 0
  done
  picker_candidates+=("$key"$'\t'"$path")
}}

{helper_prefix}_remove_shadowed_picker_candidates() {{
  local row key path shadow_row shadow_key shadow_path suffix
  local filtered_candidates=()
  for row in "${{picker_candidates[@]}}"; do
    key="${{row%%$'\t'*}}"
    path="${{row#*$'\t'}}"
    if [[ "$key" == *@* ]]; then
      suffix="${{key#*@}}"
      for shadow_row in "${{picker_candidates[@]}}"; do
        shadow_key="${{shadow_row%%$'\t'*}}"
        shadow_path="${{shadow_row#*$'\t'}}"
        if [[ "$shadow_key" == "$suffix" && "$shadow_path" == "$path" ]]; then
          continue 2
        fi
      done
    fi
    filtered_candidates+=("$row")
  done
  picker_candidates=("${{filtered_candidates[@]}}")
}}

{helper_prefix}_redraw_current_line() {{
  printf '\e[5n' > /dev/tty 2>/dev/null || true
}}

{helper_prefix}_fzf_completion() {{
  local cur="$1" output selection key path display_key display_path row
  local IFS=$'\n'
  local key_width=0 max_key_width=64
  local picker_candidates=()
  local prefix_candidates=()
  local fragment_candidates=()
  local display_candidates=()

  while IFS=$'\t' read -r key path; do
    [[ -n "$key" ]] && {helper_prefix}_add_picker_candidate "$key" "$path"
  done < <({helper_prefix}_jx_completion_picker_candidates)
{zoxide_picker_completion}  (( ${{#picker_candidates[@]}} > 0 )) || return 0

  for row in "${{picker_candidates[@]}}"; do
    key="${{row%%$'\t'*}}"
    if [[ -z "$cur" || "$key" == "$cur"* ]]; then
      prefix_candidates+=("$row")
    elif [[ "$key" == *"$cur"* ]]; then
      fragment_candidates+=("$row")
    fi
  done
  picker_candidates=("${{prefix_candidates[@]}}" "${{fragment_candidates[@]}}")
  (( ${{#picker_candidates[@]}} > 0 )) || return 0
  {helper_prefix}_remove_shadowed_picker_candidates

  for row in "${{picker_candidates[@]}}"; do
    key="${{row%%$'\t'*}}"
    (( ${{#key}} > key_width )) && key_width=${{#key}}
  done
  (( key_width > max_key_width )) && key_width=$max_key_width

  for row in "${{picker_candidates[@]}}"; do
    key="${{row%%$'\t'*}}"
    path="${{row#*$'\t'}}"
    display_key="$key"
    if (( ${{#display_key}} > key_width )); then
      display_key="${{display_key:0:$(( key_width - 1 ))}}…"
    fi
    display_path="$path"
    if [[ -n "${{HOME:-}}" && "$path" == "$HOME" ]]; then
      display_path="~"
    elif [[ -n "${{HOME:-}}" && "$path" == "$HOME"/* ]]; then
      display_path="~/${{path#"$HOME"/}}"
    fi
    display_candidates+=("$key"$'\t'"$(printf '%-*s  %s' "$key_width" "$display_key" "$display_path")")
  done

  (( ${{#display_candidates[@]}} > 0 )) || return 0

  output="$(printf '%s\n' "${{display_candidates[@]}}" | fzf --height=~60% --layout=reverse --no-sort --delimiter=$'\t' --with-nth=2 --nth=1 --query "$cur" --header='Enter: complete navigation target')" || {{
    {helper_prefix}_redraw_current_line
    COMPREPLY=()
    return 0
  }}
  {helper_prefix}_redraw_current_line
  selection="${{output##*$'\n'}}"
  key="${{selection%%$'\t'*}}"
  [[ -n "$key" ]] || return 0
  COMPREPLY=("$key")
}}
{zoxide_completion_function}
{helper_prefix}_completion() {{
  local cur="${{COMP_WORDS[COMP_CWORD]}}"
  local IFS=$'\n'
  local candidates=()
  local candidate path

  if {helper_prefix}_path_like "$cur"; then
    compopt -o filenames 2>/dev/null || true
    COMPREPLY=($(compgen -d -- "$cur"))
    return
  fi

  if command -v fzf >/dev/null 2>&1; then
    {helper_prefix}_fzf_completion "$cur"
    return
  fi
{prefer_completion}
  while IFS= read -r candidate; do
    [[ -n "$candidate" && "$candidate" == *"$cur"* ]] && {helper_prefix}_add_candidate "$candidate"
  done < <({helper_prefix}_jx_completion_candidates)
{auto_zoxide_completion}
  COMPREPLY=("${{candidates[@]}}")
}}

complete -o nospace -F {helper_prefix}_completion {completion_commands}
"#
    )
}

fn bash_navigation_zoxide_enabled_function(helper_prefix: &str, zoxide: ShellZoxideMode) -> String {
    match zoxide {
        ShellZoxideMode::Auto | ShellZoxideMode::Prefer => format!(
            r#"{helper_prefix}_zoxide_enabled() {{
  command -v zoxide >/dev/null 2>&1
}}

"#
        ),
        ShellZoxideMode::Never => String::new(),
    }
}

fn bash_navigation_jx_first_key_function(helper_prefix: &str, zoxide: ShellZoxideMode) -> String {
    match zoxide {
        ShellZoxideMode::Prefer => format!(
            r#"{helper_prefix}_jx_first_key() {{
  [[ "$1" == "default" || "$1" == "trunk" || "$1" == "root" ]]
}}

"#
        ),
        ShellZoxideMode::Auto | ShellZoxideMode::Never => String::new(),
    }
}

fn bash_navigation_resolution(helper_prefix: &str, zoxide: ShellZoxideMode) -> String {
    match zoxide {
        ShellZoxideMode::Auto => format!(
            r#"  elif (( $# == 1 )) && target="$(command jx work root --navigation "$1" 2>/dev/null)"; then
    :
  elif {helper_prefix}_zoxide_enabled && target="$(zoxide query "$@" 2>/dev/null)"; then
    :
"#
        ),
        ShellZoxideMode::Never => r#"  elif (( $# == 1 )) && target="$(command jx work root --navigation "$1" 2>/dev/null)"; then
    :
"#
        .to_owned(),
        ShellZoxideMode::Prefer => format!(
            r#"  elif (( $# == 1 )) && {helper_prefix}_jx_first_key "$1" && target="$(command jx work root --navigation "$1" 2>/dev/null)"; then
    :
  elif {helper_prefix}_zoxide_enabled && target="$(zoxide query "$@" 2>/dev/null)"; then
    :
  elif (( $# == 1 )) && target="$(command jx work root --navigation "$1" 2>/dev/null)"; then
    :
"#
        ),
    }
}

fn bash_navigation_zoxide_completion_function(
    helper_prefix: &str,
    zoxide: ShellZoxideMode,
) -> String {
    match zoxide {
        ShellZoxideMode::Auto | ShellZoxideMode::Prefer => format!(
            r#"
{helper_prefix}_add_zoxide_candidates() {{
  {helper_prefix}_zoxide_enabled || return 0
  [[ -n "$1" ]] || return 0
  while IFS= read -r path; do
    candidate="$(basename "$path")"
    {helper_prefix}_add_candidate "$candidate"
  done < <(zoxide query --list "$1" 2>/dev/null)
}}

{helper_prefix}_add_zoxide_picker_candidates() {{
  {helper_prefix}_zoxide_enabled || return 0
  [[ -n "$1" ]] || return 0
  while IFS= read -r path; do
    candidate="$(basename "$path")"
    {helper_prefix}_add_picker_candidate "$candidate" "$path"
  done < <(zoxide query --list "$1" 2>/dev/null)
}}
"#
        ),
        ShellZoxideMode::Never => String::new(),
    }
}

fn bash_navigation_zoxide_picker_completion(
    helper_prefix: &str,
    zoxide: ShellZoxideMode,
) -> String {
    match zoxide {
        ShellZoxideMode::Auto | ShellZoxideMode::Prefer => {
            format!("  {helper_prefix}_add_zoxide_picker_candidates \"$cur\"\n")
        }
        ShellZoxideMode::Never => String::new(),
    }
}

fn bash_navigation_prefer_completion(helper_prefix: &str, zoxide: ShellZoxideMode) -> String {
    match zoxide {
        ShellZoxideMode::Prefer => format!(
            r#"
  if [[ -n "$cur" ]]; then
    for candidate in default trunk root; do
      [[ "$candidate" == "$cur"* ]] && {helper_prefix}_add_candidate "$candidate"
    done
  fi
  {helper_prefix}_add_zoxide_candidates "$cur"
  if (( ${{#candidates[@]}} > 0 )); then
    COMPREPLY=("${{candidates[@]}}")
    return
  fi
"#
        ),
        ShellZoxideMode::Auto | ShellZoxideMode::Never => String::new(),
    }
}

fn bash_navigation_auto_zoxide_completion(helper_prefix: &str, zoxide: ShellZoxideMode) -> String {
    match zoxide {
        ShellZoxideMode::Auto => format!(
            r#"
  {helper_prefix}_add_zoxide_candidates "$cur"
"#
        ),
        ShellZoxideMode::Never | ShellZoxideMode::Prefer => String::new(),
    }
}

fn bash_navigation_tab_function(helper_prefix: &str, tab_command: Option<&str>) -> String {
    if tab_command.is_none() {
        return String::new();
    }

    format!(
        r#"
{helper_prefix}_tab() {{
  if (( $# != 1 )); then
    printf 'jx: opening tabs requires one resolved directory; entering directory instead\n' >&2
    {helper_prefix}_cd "$@"
    return $?
  fi

  if [[ -n "${{ZELLIJ:-}}" ]]; then
    zellij action new-tab --cwd "$1" >/dev/null
    return $?
  fi

  printf 'jx: opening tabs is only supported inside zellij; entering directory instead\n' >&2
  {helper_prefix}_cd "$1"
}}
"#
    )
}

fn bash_navigation_command_functions(
    helper_prefix: &str,
    command: &str,
    tab_command: Option<&str>,
) -> String {
    let mut functions = format!(
        r#"{command}() {{
  {helper_prefix}_resolve_and_navigate cd "$@"
}}
"#
    );
    if let Some(tab_command) = tab_command {
        functions.push_str(&format!(
            r#"
{tab_command}() {{
  {helper_prefix}_resolve_and_navigate tab "$@"
}}
"#
        ));
    }
    functions
}

fn helper_prefix(command: &str) -> String {
    format!("__jx_{command}")
}
